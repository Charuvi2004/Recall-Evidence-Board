# ------------------------------------------------------------------ learning & guardrails
with tabs[4]:
    if ev is not None:
        c = st.columns(3)
        tile(c[0], "Second-review recall", M.second_review_recall(ev), "pct",
             "Share of cards marked Remembered on their 2nd review. Above the range means cards are too easy.")
    if data["recall_test"] is not None:
        rt = M.recall_test(data["recall_test"])
        st.subheader("Objective recall test")
        if rt["means"]:
            lo, hi = rt["ci"]
            st.markdown(f"Flagged topics scored **{rt['status'].value:+.1f} points** higher than unflagged ones "
                        f"(95% CI {lo:+.1f} to {hi:+.1f}, n = {rt['status'].n} volunteers). "
                        f"Target: {rt['status'].target} · {ICON[rt['status'].result]}.")
            if lo <= 0:
                st.caption("The interval includes zero, so this sample can't rule out no effect.")
            show(charts.recall_paired(rt["per_user"], rt["means"]))
        else:
            st.info("Need at least 2 volunteers with both a flagged and an unflagged score.")
    if ev is not None:
        st.subheader("Guardrails")
        g = M.guardrails(ev, u, as_of)
        show(pd.DataFrame([{"Guardrail": k, "Value": fmt(s.value, "num" if "min" in k else "pct"),
                            "Target": s.target, "Status": ICON.get(s.result, s.result), "n": s.n}
                           for k, s in g.items()]))
    if ev is None and data["recall_test"] is None:
        need("events")

# ------------------------------------------------------------------ definitions
