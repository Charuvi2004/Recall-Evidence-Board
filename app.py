from __future__ import annotations

from pathlib import Path

import pandas as pd
import streamlit as st

import charts
import config as C
import metrics as M

HERE = Path(__file__).parent
SAMPLE_DIR = HERE / "data" / "sample"
STR_TABLES = {"survey", "interviews"}

st.set_page_config(page_title="Recall · PM dashboard", layout="wide")

ICON = {"pass": "✅ Pass", "fail": "❌ Fail", "no data": "— No data", "too little data": "— Too little data",
        "info": "ℹ️ Tracked"}


def fmt(v, kind: str = "pct") -> str:
    if v is None or pd.isna(v):
        return "—"
    return {"pct": f"{v:.0%}", "num": f"{v:.1f}", "pts": f"{v:+.1f} pts", "ratio": f"{v:.0%}"}[kind]


def show(obj, **kw):
    if hasattr(obj, "to_plotly_json"):
        st.plotly_chart(obj, width="stretch", config={"displaylogo": False}, **kw)
    else:
        st.dataframe(obj, width="stretch", hide_index=True, **kw)


def tile(col, label: str, s: M.Status, kind: str = "pct", help_text: str = ""):
    with col:
        st.metric(label, fmt(s.value, kind), help=help_text or None)
        st.caption(f"Target {s.target} · {ICON.get(s.result, s.result)} · n = {s.n}")


# ------------------------------------------------------------------ data loading
@st.cache_data(show_spinner=False)
def load_sample() -> dict[str, pd.DataFrame]:
    if not (SAMPLE_DIR / "events.csv").exists():
        import generate_sample_data as G
        import numpy as np
        rng = np.random.default_rng(42)
        SAMPLE_DIR.mkdir(parents=True, exist_ok=True)
        G.gen_events(rng).to_csv(SAMPLE_DIR / "events.csv", index=False)
        G.gen_survey(rng).to_csv(SAMPLE_DIR / "survey.csv", index=False)
        G.gen_interviews(rng).to_csv(SAMPLE_DIR / "interviews.csv", index=False)
        G.gen_recall(rng).to_csv(SAMPLE_DIR / "recall_test.csv", index=False)
    return {t: pd.read_csv(SAMPLE_DIR / f"{t}.csv", dtype=str if t in STR_TABLES else None)
            for t in M.REQUIRED_COLUMNS}


@st.cache_data(show_spinner=False)
def read_upload(raw: bytes, table: str) -> pd.DataFrame:
    import io
    return pd.read_csv(io.BytesIO(raw), dtype=str if table in STR_TABLES else None)


with st.sidebar:
    st.header("Data")
    source = st.radio("Source", ["Sample data (fake)", "Upload my CSVs"],
                      help="Sample data is generated so you can explore the dashboard. It is not real.")
    data: dict[str, pd.DataFrame | None] = {t: None for t in M.REQUIRED_COLUMNS}
    if source.startswith("Sample"):
        data = load_sample()
    else:
        labels = {"events": "Extension events (events.csv)", "survey": "Survey responses (survey.csv)",
                  "interviews": "Interview coding (interviews.csv)", "recall_test": "Recall test (recall_test.csv)"}
        for t, lab in labels.items():
            f = st.file_uploader(lab, type="csv", key=t)
            if f is not None:
                df = read_upload(f.getvalue(), t)
                miss = M.missing_columns(df, t)
                if miss:
                    st.error(f"{t}: missing columns {', '.join(miss)}. See the README for the schema.")
                else:
                    data[t] = df
        st.caption("Column definitions are in the README and the Definitions tab.")

is_sample = source.startswith("Sample")
st.title("Recall · pilot and research dashboard")
if is_sample:
    st.warning("**Sample data.** Every number below is generated by `generate_sample_data.py`. "
               "It is not a finding. Don't quote it on a resume, in a write-up or in an interview.", icon="⚠️")

ev = M.prep_events(data["events"]) if data["events"] is not None else None
as_of = None
if ev is not None and not ev.empty:
    with st.sidebar:
        d = st.date_input("Data as of", value=ev.ts.max().date(),
                          min_value=ev.ts.min().date(), max_value=ev.ts.max().date())
    as_of = pd.Timestamp(d) + pd.Timedelta(days=1) - pd.Timedelta(seconds=1)
    ev = ev[ev.ts <= as_of]
    u = M.users(ev, as_of)
    war = M.weekly_active_reviewers(ev, u, as_of)
    last_wk = M.last_complete_week(war)

tabs = st.tabs(["Overview", "Research (Phase 1)", "Activation", "Retention", "Learning & guardrails", "Definitions"])


def need(table: str) -> bool:
    if data[table] is None:
        st.info(f"Upload **{table}.csv** in the sidebar to see this section.")
        return False
    return True


# ------------------------------------------------------------------ overview
with tabs[0]:
    if ev is None:
        st.info("Upload **events.csv** to see pilot metrics, or switch to sample data.")
    else:
        latest = war[war.week_start == last_wk] if last_wk is not None else war.iloc[0:0]
        ns_val = float(latest.share.iloc[0]) if len(latest) else None
        ns = M._status(ns_val, None if ns_val is None else ns_val >= C.NORTH_STAR_TARGET,
                       f"≥ {C.NORTH_STAR_TARGET:.0%}", int(latest.installed_base.iloc[0]) if len(latest) else 0)
        act_val = u.activated.mean() if len(u) else None
        act = M._status(act_val, None if act_val is None else act_val >= C.ACTIVATION_TARGET,
                        f"≥ {C.ACTIVATION_TARGET:.0%}", len(u))
        r1 = M.retention(ev, u, as_of, 1, C.RETENTION_W1_TARGET)
        r4 = M.retention(ev, u, as_of, 4, C.RETENTION_W4_TARGET)

        c = st.columns(4)
        tile(c[0], "North Star · Weekly Active Reviewers", ns,
             help_text=f"Installed users who reviewed on {C.NORTH_STAR_MIN_REVIEW_DAYS}+ days in the last complete week"
                       + (f" (week of {last_wk:%d %b})" if last_wk is not None else ""))
        tile(c[1], "Activation", act, help_text="Course + 3 flags + first review within 72h of install")
        tile(c[2], "Week-1 review retention", r1, help_text="Activated users who reviewed in days 7-13 after install")
        tile(c[3], "Week-4 review retention", r4, help_text="Activated users who reviewed in days 28-34 after install")

        show(charts.war_line(war))

        eng = M.weekly_engagement(ev, last_wk)
        rows = [
            ("North Star", "Weekly Active Reviewers", ns, "pct"),
            ("Activation", "Activated learners", act, "pct"),
            ("Engagement", "Flags per hour watched", M.flags_per_hour(ev), "num"),
            ("Engagement", "Review days per active learner", eng["review_days"], "num"),
            ("Engagement", "Videos completed per active learner", eng["videos"], "num"),
            ("Retention", "Week-1 review retention", r1, "pct"),
            ("Retention", "Week-4 review retention", r4, "pct"),
            ("Quality", "Second-review recall", M.second_review_recall(ev), "pct"),
        ]
        if data["recall_test"] is not None:
            rows.append(("Quality", "Recall test gap (flagged − unflagged)",
                         M.recall_test(data["recall_test"])["status"], "pts"))
        rows += [("Guardrail", k, v, "num" if "min" in k else "pct") for k, v in M.guardrails(ev, u, as_of).items()]
        table = pd.DataFrame([{"Type": t, "Metric": m, "Value": fmt(s.value, k), "Target": s.target,
                               "Status": ICON.get(s.result, s.result), "n": s.n} for t, m, s, k in rows])
        st.subheader("All metrics vs. target")
        show(table)
        st.download_button("Download this table (CSV)", table.to_csv(index=False), "recall_metrics.csv", "text/csv")

# ------------------------------------------------------------------ research
with tabs[1]:
    if need("survey"):
        survey = data["survey"]
        interviews = data["interviews"] if data["interviews"] is not None else \
            pd.DataFrame(columns=M.REQUIRED_COLUMNS["interviews"])
        seg = M.segment(survey)
        st.markdown(f"**{len(seg)}** of {len(survey)} survey respondents are in the target segment "
                    f"(preparing for {C.SEGMENT_GOAL}); **{interviews.participant_id.nunique()}** interviewees "
                    f"(goal {C.INTERVIEW_TARGET_N}). Thresholds were set before data collection.")
        sc = M.kill_scorecard(survey, interviews)
        sc["result"] = sc.result.map(lambda r: ICON.get(r, r))
        st.subheader("Kill / continue criteria")
        show(sc.rename(columns={"check": "Check", "hypothesis": "Hypothesis", "evidence": "Evidence",
                                "result": "Result", "if it fails": "If it fails"}))

        left, right = st.columns(2)
        with left:
            pf = M.pain_frequency(seg)
            show(charts.share_bars(pf.pain, pf.share_2plus, "Happened 2+ times in the last 2 weeks (segment)"))
        with right:
            dev = seg.device.value_counts(normalize=True)
            show(charts.share_bars(dev.index.str.capitalize(), dev.values, "Device used for most YouTube learning",
                                   height=260))
            top = seg.top_problem.value_counts(normalize=True)
            show(charts.share_bars(top.index.str.replace("_", " ").str.capitalize(), top.values,
                                   "The ONE problem they most want solved", height=280))

        if not interviews.empty:
            st.subheader("Interview coding")
            tally = (interviews.assign(unprompted_support=(interviews.verdict == "supports")
                                       & (interviews.unprompted.str.lower() == "yes"))
                     .groupby("hypothesis")
                     .agg(supports=("verdict", lambda v: (v == "supports").sum()),
                          contradicts=("verdict", lambda v: (v == "contradicts").sum()),
                          not_discussed=("verdict", lambda v: (v == "not_discussed").sum()),
                          raised_unprompted_and_supports=("unprompted_support", "sum"))
                     .reset_index())
            show(tally)
            with st.expander("Supporting quotes"):
                q = interviews[(interviews.verdict == "supports") & interviews.quote.fillna("").ne("")]
                show(q[["hypothesis", "participant_id", "quote"]].sort_values("hypothesis"))

# ------------------------------------------------------------------ activation
